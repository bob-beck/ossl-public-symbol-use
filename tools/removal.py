#!/usr/bin/env python3
"""removal -- libcrypto removal and deprecation candidate lists.

Reads a symuse database (with symbol_intro, see refresh.py) and an
OpenSSL tree, and writes CSV lists of non-deprecated libcrypto functions
with no outside users or exactly one.  The tree's ssl/, apps/,
providers/ and fuzz/ are scanned for in-tree callers; test/ is scanned
and reported but never blocks a candidate.

Usage:
    removal.py <db> <openssl-tree> <outdir> [--extracted FILE]
               [--extracted-dir DIR ...]

--extracted names a file of symbols handled elsewhere (one per line,
for example those an extraction branch deprecates); they are moved out
of the other lists into extracted.csv.  --extracted-dir names a crypto/
subdirectory leaving libcrypto with them (crypto/cmp, say); a reference
from there does not keep an unused function alive.

Unused functions with no ssl/apps/providers/fuzz caller and no trap are
split by references from libcrypto's own crypto/ sources.  A line
beginning in column 0 that contains NAME( and does not end in ';' is
taken as the definition; any other mention is a reference.  Names that
never appear written out are generated by macros (the ASN.1 families,
EVP cipher getters) and cannot be classified lexically.

Outputs, in <outdir>:
    unused-dead.csv                  no users, never referenced in crypto/
    unused-internal.csv              no users, referenced in crypto/
    unused-generated.csv             no users, macro-generated, unclassified
    unused-with-caveat.csv           no users, but a caller or a trap
    single-user.csv                  one user, no in-tree caller
    single-user-internal-caller.csv  one user and an in-tree caller
    extracted.csv                    rows of the above named by --extracted
    libssl-exports.csv               rows of the above that libssl calls
    deprecated-unused.csv            deprecated, no users
    deprecated-single-user.csv       deprecated, one user

The non-deprecated lists carry successor: evidence that the function
is a documented replacement for something deprecated, so it is waiting
to be adopted rather than dead (see successors()).

The two deprecated lists carry deprecated_in (the release named by the
DEPRECATEDIN_ condition) and crypto_status: dead, internal (referenced
elsewhere in crypto/, files in crypto_refs, or called from ssl/, apps/,
providers/ or fuzz/, named in internal_callers) or generated.
"""

import argparse
import csv
import os
import re
import sqlite3
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import symuse  # noqa: E402

AREAS = ("ssl", "apps", "providers", "fuzz", "test")
BLOCKING = ("ssl", "apps", "providers", "fuzz")
PRE_3 = ("1.0.2-or-earlier", "1.1.0", "1.1.1")
COLUMNS = ["symbol", "family", "introduced", "era", "users", "user",
           "internal_callers", "test", "pair_used", "asn1_partial",
           "successor"]
STRIP_RE = re.compile(r"^(d2i|i2d|i2o|o2i|i2s|s2i|i2v|v2i|i2r|r2i"
                      r"|PEM_read_bio|PEM_write_bio|PEM_read|PEM_write)_")
PREFIX_RE = re.compile(r"(OSSL_[A-Z0-9]+|EVP_[A-Z0-9]+|X509V3|X509v3"
                       r"|[A-Za-z0-9]+)")
DEPRECATED_RE = re.compile(r"DEPRECATEDIN_([0-9_]+)")
DEPRECATED_COLUMNS = ["symbol", "family", "deprecated_in", "introduced",
                      "users", "user", "internal_callers", "test",
                      "crypto_status", "crypto_refs"]


def area_callers(tree, names):
    """area -> set of names appearing in that area's C sources."""
    found = {}
    for area in AREAS:
        hit = set()
        for dirpath, _, filenames in os.walk(os.path.join(tree, area)):
            for fn in filenames:
                if os.path.splitext(fn)[1] not in (".c", ".h", ".inc"):
                    continue
                with open(os.path.join(dirpath, fn), encoding="utf-8",
                          errors="replace") as fh:
                    code = symuse.NOISE_RE.sub(" ", fh.read())
                hit |= set(symuse.IDENT_RE.findall(code)) & names
        found[area] = hit
    return found


def crypto_references(tree, names, skip_dirs):
    """(written, referenced): names written out in crypto/ (a definition,
    or any mention inside skip_dirs), and name -> set of crypto/ files
    outside skip_dirs referencing it.
    """
    defined = set()
    referenced = {}
    root = os.path.join(tree, "crypto")
    for dirpath, _, filenames in os.walk(root):
        for fn in filenames:
            if os.path.splitext(fn)[1] not in (".c", ".h", ".inc"):
                continue
            path = os.path.join(dirpath, fn)
            rel = os.path.relpath(path, tree)
            skipped = any(rel == d or rel.startswith(d.rstrip("/") + "/")
                          for d in skip_dirs)
            with open(path, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            # Keep line structure so column-0 definitions stay recognisable.
            text = symuse.NOISE_RE.sub(
                lambda m: "\n" * m.group(0).count("\n") or " ", text)
            for line in text.split("\n"):
                for name in set(symuse.IDENT_RE.findall(line)) & names:
                    if (line[:1] not in (" ", "\t", "#")
                            and re.search(r"\b%s\s*\(" % re.escape(name), line)
                            and not line.rstrip().endswith(";")):
                        defined.add(name)
                    elif skipped:
                        defined.add(name)
                    else:
                        referenced.setdefault(name, set()).add(rel)
    return defined, referenced


def crypto_files(tree, name):
    out = subprocess.run(
        ["grep", "-rlw", "--include=*.c", name, os.path.join(tree, "crypto")],
        capture_output=True, text=True)
    return len(out.stdout.split())


def family(name, conditions):
    guards = [g for g in (conditions or "").split(",")
              if g and not g.startswith("DEPRECATED")]
    if guards:
        return guards[0]
    prefix = PREFIX_RE.match(STRIP_RE.sub("", name)).group(1)
    return "X509V3" if prefix == "X509v3" else prefix


def partner(name):
    for suffix, other in (("_new", "_free"), ("_free", "_new"),
                          ("_up_ref", "_free")):
        if name.endswith(suffix):
            return name[:-len(suffix)] + other
    return None


def version_key(version):
    return tuple(int(p) for p in version.split(".") if p.isdigit())


def successors(tree, db):
    """name -> evidence that the function replaces a deprecated one.

    A function OpenSSL points callers to is waiting to be adopted, so
    "unused" means "not yet", not "dead".  Evidence, any of:
      - named in an OSSL_DEPRECATEDIN_*_FOR("use NAME()") annotation;
      - named in a POD paragraph that also names a deprecated function
        and says deprecated plus instead/replace/use/in favour;
      - an _ex/_exN form of an existing function;
      - a get_/get0_/get1_/set0_/set1_ rename of a deprecated function,
        or of a header macro that now expands to it.
    """
    sym = dict(db.execute("SELECT name, deprecated FROM symbol"))
    funcs = {r[0] for r in db.execute(
        "SELECT name FROM symbol WHERE origin IN ('libcrypto', 'libssl')")}
    dep = {n for n, d in sym.items() if d}
    aliases = set(db.execute("SELECT macro, symbol FROM macro_calls"))
    found = {}

    def add(name, why):
        found.setdefault(name, set()).add(why)

    incdir = os.path.join(tree, "include", "openssl")
    for fn in os.listdir(incdir):
        with open(os.path.join(incdir, fn), encoding="utf-8",
                  errors="replace") as fh:
            text = fh.read()
        for m in re.finditer(
                r'OSSL_DEPRECATEDIN_[0-9_]+_FOR\("([^"]*)"\)\s*([^;]*;)', text):
            old = re.findall(r"\b([A-Za-z_]\w*)\s*\(", m.group(2))
            for name in re.findall(r"\b([A-Za-z_]\w*)\(\)", m.group(1)):
                if name in funcs:
                    add(name, "header: use instead of %s"
                        % (old[-1] if old else "?"))
    for sub in ("man3", "man7"):
        docdir = os.path.join(tree, "doc", sub)
        for fn in os.listdir(docdir):
            if not fn.endswith(".pod"):
                continue
            with open(os.path.join(docdir, fn), encoding="utf-8",
                      errors="replace") as fh:
                text = fh.read()
            for para in re.split(r"\n\s*\n", text):
                if not re.search(r"deprecat", para, re.I) or not re.search(
                        r"\b(instead|replac|use|in favou?r)", para, re.I):
                    continue
                names = (set(re.findall(r"B<([A-Za-z_]\w*)>", para))
                         | set(re.findall(r"\b([A-Za-z_]\w*)\(\)", para)))
                olds = sorted(n for n in names if n in dep)
                if olds:
                    for name in names & funcs - dep:
                        add(name, "doc %s/%s with deprecated %s"
                            % (sub, fn, olds[0]))
    for name in funcs - dep:
        m = re.match(r"^(.*)_ex(\d*)$", name)
        if m:
            base = m.group(1)
            if m.group(2) and int(m.group(2)) > 2:
                base += "_ex%d" % (int(m.group(2)) - 1)
            elif m.group(2):
                base += "_ex"
            if base in sym:
                add(name, "_ex form of %s" % base)
        for part in ("_get0_", "_get1_", "_get_", "_set0_", "_set1_"):
            if part in name:
                old = name.replace(part, "_", 1)
                if old in dep or (old, name) in aliases:
                    add(name, "renamed from %s" % old)
    return {n: "; ".join(sorted(w)) for n, w in found.items()}


